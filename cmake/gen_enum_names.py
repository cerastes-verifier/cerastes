"""Generate enumerator-name functions for EDG IL enums from il_def.h.

EDG's own name tables (il_display.c) are static, so cerastes derives its own
from the pinned header at build time.  Preprocessor conditionals inside an
enum body are copied through, so an enumerator that exists only under some
configuration is only named under that configuration.

usage: gen_enum_names.py <il_def.h> <out.inc> <enum_name>...
"""
import re
import sys


def strip_comments(text):
    # Keep newlines so line structure survives.
    def repl(m):
        return "\n" * m.group(0).count("\n")
    return re.sub(r"/\*.*?\*/", repl, text, flags=re.S)


def enum_body(text, name):
    m = re.search(r"^enum\s+" + re.escape(name) + r"\b[^{;]*\{", text, flags=re.M)
    if not m:
        sys.exit("gen_enum_names.py: enum %s not found" % name)
    start = m.end()
    end = text.index("};", start)
    return text[start:end]


def cases(body):
    out, buf = [], ""

    def flush_piece(piece):
        m = re.match(r"\s*([A-Za-z_]\w*)\s*(=\s*(.*))?$", piece, flags=re.S)
        # `name = other_enumerator` is a synonym (tk_enum = tk_integer): naming
        # it would duplicate a case value.
        if m and not (m.group(3) and re.search(r"[A-Za-z_]", m.group(3))):
            out.append("  case %s: return \"%s\";" % (m.group(1), m.group(1)))

    for line in body.split("\n"):
        s = line.strip()
        if s.startswith("#"):
            if re.match(r"#\s*(if|ifdef|ifndef|elif|else|endif)\b", s):
                out.append(s)
            continue
        buf += " " + line
        while "," in buf:
            piece, buf = buf.split(",", 1)
            flush_piece(piece)
    flush_piece(buf)
    return out


def main():
    if len(sys.argv) < 4:
        sys.exit(__doc__)
    header, outpath, names = sys.argv[1], sys.argv[2], sys.argv[3:]
    text = strip_comments(open(header, encoding="utf-8", errors="replace").read())
    lines = ["// Generated by cmake/gen_enum_names.py from il_def.h; do not edit."]
    for n in names:
        lines.append("const char* name_of(%s v) {" % n)
        lines.append(" switch (v) {")
        cs = cases(enum_body(text, n))
        count = sum(1 for c in cs if c.lstrip().startswith("case "))
        # Sanity: a parse that finds (almost) nothing means the header changed
        # shape; fail the build rather than emit a table of "<enum?>".
        if count < 3:
            sys.exit("gen_enum_names.py: enum %s parsed to only %d enumerators" % (n, count))
        lines += cs
        lines.append("  default: return \"<%s?>\";" % n)
        lines.append(" }")
        lines.append("}")
        lines.append("")
    open(outpath, "w").write("\n".join(lines) + "\n")


main()
